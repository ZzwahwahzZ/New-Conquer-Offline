#!/usr/bin/env python3
"""Regenerate root CREDITS.md from the exact downloaded asset manifests."""
from __future__ import annotations
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
PACK=ROOT/"assets"/"wuxia_imperial_pack"
def read(path):
 return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
def main():
 china=read(PACK/"asset_manifest.json")
 quaternius=read(PACK/"quaternius_manifest.json")
 poly=read(PACK/"paving"/"polyhaven_pbr"/"manifest.json")
 ambient=read(PACK/"paving"/"ambientcg"/"manifest.json")
 lines=[
 "# Wuxia Imperial Pack — Asset Credits & License Register",
 "",
 "This file is regenerated by tools/generate_wuxia_credits.py from downloaded manifests. Only assets actually present in the Wuxia pack are listed as included; reviewed-but-not-downloaded sources are clearly separated.",
 "",
 "## Accepted license policy",
 "",
 "- **CC0 1.0**: accepted for commercial use, modification and redistribution.",
 "- **CC BY 4.0**: accepted when the exact creator, asset title, source URL and license URL are retained; derivative changes are disclosed.",
 "- CC BY-SA, NC, ND, custom restricted licenses and unclear license records are not automatically accepted.",
 "- Every downloaded file is hashed and its source, creator and license are stored in its manifest.",
 "",
 "## Included 3D assets",
 "",
 "| Asset / pack | Creator | License | Source |",
 "|---|---|---|---|"
 ]
 for item in china.get("assets",[]):
  name=str(item.get("name","Unnamed asset")).replace("|","/")
  author=str(item.get("author","3DAssets.dev")).replace("|","/")
  license=str(item.get("license","unverified"))
  source=str(item.get("source","")).replace("|","%7C")
  lines.append(f"| {name} | {author} | {license} | {source} |")
 for slug,meta in quaternius.get("packs",{}).items():
  lines.append(f"| Quaternius {slug.replace('_',' ').title()} | Quaternius | {meta.get('license','CC0-1.0')} | {meta.get('page','https://quaternius.com/')} |")
 for aid,meta in poly.get("assets",{}).items():
  author=str(meta.get("author","Poly Haven contributor"))
  lines.append(f"| Poly Haven — {meta.get('name',aid)} | {author} | CC0-1.0 | {meta.get('source','https://polyhaven.com/a/'+aid)} |")
 for aid,meta in ambient.get("assets",{}).items():
  lines.append(f"| ambientCG — {aid} | {meta.get('author','ambientCG contributors')} | {meta.get('license','CC0-1.0')} | {meta.get('source','https://ambientcg.com/')} |")
 lines += [
 "",
 "## Reviewed CC-BY / CC0 sources not yet bundled",
 "",
 "These are discovery records only. They are not counted as included game assets until the actual downloadable file is acquired, validated and added to a manifest.",
 "",
 "| Asset | Creator | License shown by source | Source |",
 "|---|---|---|---|",
 "| Chinese Pagoda | SibeYu | CC BY | https://sketchfab.com/3d-models/chinese-pagoda-9368be07f47949e2b6eaa962ea9c58ad |",
 "| Chinese Buddhist Pagoda | Aaron Huo | CC BY | https://sketchfab.com/3d-models/chinese-buddhist-pagoda-c95a8214aa6147629d1442c02261d351 |",
 "| Small Chinese Imperial Style Building | andertan | CC BY | https://sketchfab.com/3d-models/small-chinese-imperial-style-building-631615777ba4421a98814559dc2d4c5a |",
 "| Chinese Guardian Lion | polunovsskaya | CC BY | https://sketchfab.com/3d-models/chinese-guardian-lion-1705bc3d4bb54ee0a609f4e24e38fe24 |",
 "| Chinese House | Katydid | CC BY | https://sketchfab.com/3d-models/chinese-house-5b4804924d694f4dbf5d2e3fcaaf73fa |",
 "| Chinese Gate | Triative | Free Standard (not CC BY) | https://sketchfab.com/3d-models/chinese-gate-8357c2792f9a4d54bb18aeb9dc1d14af |",
 "| Modular Temple | Keith at Fertile Soil Productions | CC0 | https://opengameart.org/content/modular-temple-3d-models |",
 "",
 "## Texture author notes",
 "",
 "- Poly Haven texture authors are listed individually above; the maps are CC0 1.0.",
 "- ambientCG materials are CC0 1.0; source pages and map hashes are recorded in paving/ambientcg/manifest.json.",
 "",
 "## Change log",
 "",
 "- This register is generated from the exact asset manifests on each CI build.",
 "- CC-BY attribution is mandatory whenever a CC-BY asset is moved from the reviewed list into the included library."
 ]
 (ROOT/"CREDITS.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
 print(f"WUXIA_CREDITS_GENERATED: included_china={len(china.get('assets',[]))} quaternius_packs={len(quaternius.get('packs',{}))} polyhaven={len(poly.get('assets',{}))} ambientcg={len(ambient.get('assets',{}))}")
if __name__=="__main__": main()
