#!/usr/bin/env python3
"""Regenerate root CREDITS.md from the exact downloaded asset manifests."""
from __future__ import annotations
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
PACK=ROOT/"assets"/"wuxia_imperial_pack"
def read(path):
 return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
def main():
 china=read(PACK/"asset_manifest.json")
 quaternius=read(PACK/"quaternius_manifest.json")
 poly=read(PACK/"paving"/"polyhaven_pbr"/"manifest.json")
 ambient=read(PACK/"paving"/"ambientcg"/"manifest.json")
 opengameart=read(PACK/"opengameart_manifest.json")
 lines=[
 "# Wuxia Imperial Pack — Asset Credits & License Register",
 "",
 "This file is regenerated by tools/generate_wuxia_credits.py from downloaded manifests. Only assets actually present in the Wuxia pack are listed as included; unverified or unavailable sources are never represented as included.",
 "",
 "## Accepted license policy",
 "",
 "- **CC0 1.0**: accepted for commercial use, modification and redistribution.",
 "- **CC BY**: accepted only when the exact source license URL and creator/attribution record are verified and retained; derivative changes are disclosed.",
 "- CC BY-SA, NC, ND, custom restricted licenses and unclear license records are not automatically accepted.",
 "- Every downloaded file is hashed and its source, creator and license are stored in its manifest.",
 "",
 "## Included 3D assets",
 "",
 "AI provenance reported by the source pack: " + str(china.get("ai_assisted","not supplied by source")),
 "",
 "| Asset / pack | Creator | License | License URL | Required attribution | Source |",
 "|---|---|---|---|---|---|"
 ]
 for item in china.get("assets",[]):
  name=str(item.get("name","Unnamed asset")).replace("|","/")
  author=str(item.get("author","3DAssets.dev")).replace("|","/")
  license=str(item.get("license","unverified"))
  source=str(item.get("source","")).replace("|","%7C")
  attribution=str(item.get("attribution_text","")).replace("|","/")
  license_url=str(item.get("license_url",""))
  lines.append(f"| {name} | {author} | {license} | {license_url} | {attribution} | {source} |")
 for slug,meta in quaternius.get("packs",{}).items():
  lines.append(f"| Quaternius {slug.replace('_',' ').title()} | Quaternius | {meta.get('license','CC0-1.0')} | https://creativecommons.org/publicdomain/zero/1.0/ | — | {meta.get('page','https://quaternius.com/')} |")
 for aid,meta in poly.get("assets",{}).items():
  author=str(meta.get("author","Poly Haven contributor"))
  lines.append(f"| Poly Haven — {meta.get('name',aid)} | {author} | CC0-1.0 | https://creativecommons.org/publicdomain/zero/1.0/ | — | {meta.get('source','https://polyhaven.com/a/'+aid)} |")
 for aid,meta in ambient.get("assets",{}).items():
  lines.append(f"| ambientCG — {aid} | {meta.get('author','ambientCG contributors')} | {meta.get('license','CC0-1.0')} | https://creativecommons.org/publicdomain/zero/1.0/ | — | {meta.get('source','https://ambientcg.com/')} |")
 for model in opengameart.get("models",[]):
  lines.append(f"| OpenGameArt — {model.get('name','Modular Temple part')} | {opengameart.get('creator','Unknown creator')} | {opengameart.get('license','CC0-1.0')} | {opengameart.get('license_url','https://creativecommons.org/publicdomain/zero/1.0/')} | — | {opengameart.get('source','https://opengameart.org/')} |")
 lines += [
 "",
 "## CC-BY source handling",
 "",
 "The download and attribution pipeline accepts CC-BY when the source metadata supplies a verified license URL and creator record. OpenGameArt modular temple parts included above are downloaded and validated. Sketchfab models are not represented as included until their actual files, license and author metadata have been downloaded and validated. No guessed or placeholder creator credits are used.",
 "",
 "## Texture author notes",
 "",
 "- Poly Haven texture authors are listed individually above; the maps are CC0 1.0.",
 "- ambientCG materials are CC0 1.0; source pages and map hashes are recorded in paving/ambientcg/manifest.json.",
 "",
 "## Change log",
 "",
 "- This register is generated from the exact asset manifests on each CI build.",
 "- CC-BY attribution is mandatory for every included CC-BY asset."
 ]
 (ROOT/"CREDITS.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
 print(f"WUXIA_CREDITS_GENERATED: included_china={len(china.get('assets',[]))} quaternius_packs={len(quaternius.get('packs',{}))} polyhaven={len(poly.get('assets',{}))} ambientcg={len(ambient.get('assets',{}))} opengameart={len(opengameart.get('models',[]))}")
if __name__=="__main__": main()
